// ============================================================================
// games/rhythm/theme.js —— 三套背景主题（同一套几何，只换光与色）
// ----------------------------------------------------------------------------
// 三个背景不是三张不同的画，而是**同一条跑道在不同光线下的样子**：
// 地平线位置、山形、跑道透视、判定线全部一样，只有天空渐层、光源、远山
// 色温、地面色温、地平线光色在变。
//
// 为什么这么做：
//   1. 美术成本 —— 换元素要重画跑道两边的所有东西，工作量是换色的三倍；
//   2. **患者不迷路** —— 康复训练里最怕「界面一变就不会用了」。背景只是
//      心情，操作语言必须稳定；
//   3. 车道色温（左冷青 / 中暖白 / 右琥珀）**三套完全一致，永远不改**。
//      那是功能语义，不是装饰。换背景就换掉它，等于让患者重新学一遍左右。
//
// 三套都是暗调，理由只有一个：**高明度底色撑不起辉光**。糖果色那版就是
// 明度太高，所有光效画上去直接被洗没（这是本项目踩过最贵的一条）。
//
// 每套主题的字段：
//   sky[]        天空渐层 [{at, color}]（at = 距地平线的比例，0 = 天顶）
//   light        光源本体 {x(±比例), y(距地平线px), r, core[], glow[], beam[]}
//   ridge[]      三层远山剪影颜色（由远到近，必须越来越暗）
//   haze         山脚薄雾 rgb 串
//   ground[]     地面渐层（第一档必须贴住天空最底部颜色，否则天地之间有硬边）
//   groundGlow   地平线附近的地面天光 rgb
//   road[]       路面渐层
//   lanes[]      三条车道的极弱色温
//   edge         跑道边线 rgb
//   farFade      远端收口色 rgb
//   stars        星点数量（0 = 无）
//   city         远城灯火数量（0 = 无）
// ============================================================================

